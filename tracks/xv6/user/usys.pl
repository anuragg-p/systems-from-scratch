#!/usr/bin/perl -w

# Generate usys.S, the user-side entry points of the system calls.
# Each one puts the call number in a7 and executes ecall; the kernel puts
# the result in a0, which is where C expects a return value.

print "# generated by usys.pl - do not edit\n";

print "#include \"kernel/syscall.h\"\n";

sub entry {
    my $name = shift;
    print ".global $name\n";
    print "${name}:\n";
    print " li a7, SYS_${name}\n";
    print " ecall\n";
    print " ret\n";
}

